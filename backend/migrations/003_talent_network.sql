CREATE TABLE talent_accounts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 name VARCHAR(100) NOT NULL,
 role ENUM('artist','hirer') NOT NULL,
 status ENUM('pending','approved','suspended') NOT NULL DEFAULT 'pending',
 city VARCHAR(100) NOT NULL DEFAULT '',
 profession VARCHAR(100) NOT NULL DEFAULT '',
 languages VARCHAR(300) NOT NULL DEFAULT '',
 skills VARCHAR(500) NOT NULL DEFAULT '',
 organisation VARCHAR(150) NOT NULL DEFAULT '',
 bio TEXT,
 credits TEXT,
 availability VARCHAR(300) NOT NULL DEFAULT '',
 showreel VARCHAR(500) NOT NULL DEFAULT '',
 image_id INT UNSIGNED NULL,
 visible BOOLEAN NOT NULL DEFAULT FALSE,
 consent_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 contact_checked BOOLEAN NOT NULL DEFAULT FALSE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE talent_shortlists (
 account_id INT UNSIGNED NOT NULL,
 artist_id INT UNSIGNED NOT NULL,
 PRIMARY KEY(account_id,artist_id),
 FOREIGN KEY(account_id) REFERENCES talent_accounts(id) ON DELETE CASCADE,
 FOREIGN KEY(artist_id) REFERENCES talent_accounts(id) ON DELETE CASCADE
);
CREATE TABLE talent_enquiries (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 sender_id INT UNSIGNED NOT NULL,
 artist_id INT UNSIGNED NOT NULL,
 project VARCHAR(200) NOT NULL,
 message TEXT NOT NULL,
 status ENUM('new','interested','declined') NOT NULL DEFAULT 'new',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(sender_id) REFERENCES talent_accounts(id) ON DELETE CASCADE,
 FOREIGN KEY(artist_id) REFERENCES talent_accounts(id) ON DELETE CASCADE
);
CREATE TABLE production_projects (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 account_id INT UNSIGNED NOT NULL,
 title VARCHAR(200) NOT NULL,
 budget DECIMAL(14,2) NOT NULL DEFAULT 0,
 currency VARCHAR(3) NOT NULL DEFAULT 'INR',
 language VARCHAR(100) NOT NULL DEFAULT '',
 timeline VARCHAR(500) NOT NULL DEFAULT '',
 goals TEXT,
 script_filename VARCHAR(100) NULL,
 script_name VARCHAR(255) NULL,
 script_text MEDIUMTEXT,
 plan JSON NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(account_id) REFERENCES talent_accounts(id) ON DELETE CASCADE
);
