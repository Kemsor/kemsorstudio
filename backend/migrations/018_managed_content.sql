CREATE TABLE cms_managed_content (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 kind ENUM('legal','hero') NOT NULL,
 slug VARCHAR(190) NOT NULL,
 draft JSON NOT NULL,
 published JSON NULL,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 updated_by INT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY(kind,slug),
 FOREIGN KEY(updated_by) REFERENCES cms_users(id) ON DELETE SET NULL
);
CREATE TABLE cms_managed_revisions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 content_id INT UNSIGNED NOT NULL,
 revision INT UNSIGNED NOT NULL,
 action VARCHAR(30) NOT NULL,
 snapshot JSON NOT NULL,
 created_by INT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY(content_id,revision),
 FOREIGN KEY(content_id) REFERENCES cms_managed_content(id) ON DELETE CASCADE,
 FOREIGN KEY(created_by) REFERENCES cms_users(id) ON DELETE SET NULL
);
