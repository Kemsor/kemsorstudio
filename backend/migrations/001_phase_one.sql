CREATE TABLE IF NOT EXISTS cms_migrations (name VARCHAR(190) PRIMARY KEY, applied_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS cms_users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role ENUM('admin','editor','enquiry_manager') NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS cms_sessions (id CHAR(64) PRIMARY KEY, data MEDIUMTEXT NOT NULL, expires_at DATETIME NOT NULL, INDEX(expires_at));
CREATE TABLE IF NOT EXISTS cms_entries (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, type ENUM('news','blog','career','team','home','page','legal') NOT NULL,
 title VARCHAR(200) NOT NULL, slug VARCHAR(190) NOT NULL, summary TEXT NOT NULL, body MEDIUMTEXT NOT NULL,
 image_id INT UNSIGNED NULL, metadata JSON NOT NULL, status ENUM('draft','published','archived') NOT NULL DEFAULT 'draft',
 published_at DATETIME NULL, created_by INT UNSIGNED NULL, updated_by INT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY(type,slug), INDEX(type,status,published_at), FOREIGN KEY(created_by) REFERENCES cms_users(id) ON DELETE SET NULL,
 FOREIGN KEY(updated_by) REFERENCES cms_users(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS cms_media (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, filename VARCHAR(255) NOT NULL, original_name VARCHAR(255) NOT NULL,
 mime VARCHAR(100) NOT NULL, size INT UNSIGNED NOT NULL, alt VARCHAR(300) NOT NULL,
 created_by INT UNSIGNED NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(created_by) REFERENCES cms_users(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS cms_settings (name VARCHAR(100) PRIMARY KEY, value JSON NOT NULL, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS cms_enquiries (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, category ENUM('business','partnerships','press','careers','production','copyright','general') NOT NULL,
 name VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL, organisation VARCHAR(150) NOT NULL DEFAULT '',
 subject VARCHAR(200) NOT NULL, message TEXT NOT NULL,
 status ENUM('new','in_review','contacted','closed','spam') NOT NULL DEFAULT 'new',
 assigned_to INT UNSIGNED NULL, consent_at DATETIME NOT NULL, consent_version VARCHAR(100) NOT NULL,
 attachment_filename VARCHAR(255) NULL, attachment_name VARCHAR(255) NULL, attachment_mime VARCHAR(100) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX(status,category,created_at), FOREIGN KEY(assigned_to) REFERENCES cms_users(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS cms_enquiry_notes (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, enquiry_id INT UNSIGNED NOT NULL, user_id INT UNSIGNED NULL,
 note TEXT NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(enquiry_id) REFERENCES cms_enquiries(id) ON DELETE CASCADE, FOREIGN KEY(user_id) REFERENCES cms_users(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS cms_audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NULL, action VARCHAR(100) NOT NULL,
 target_type VARCHAR(100) NOT NULL, target_id VARCHAR(190) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES cms_users(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS cms_rate_limits (id CHAR(64) PRIMARY KEY, attempts INT UNSIGNED NOT NULL, expires_at DATETIME NOT NULL, INDEX(expires_at));
